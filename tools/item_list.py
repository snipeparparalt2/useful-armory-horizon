#!/usr/bin/env python3
"""Write docs/items.md: every item and block of the content mod, read from content/.

    python3 tools/item_list.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NS = ROOT / "content" / "data" / "useful_armory" / "horizon"
LANG = json.loads((ROOT / "content" / "assets" / "useful_armory" / "lang" / "en_us.json").read_text())
SETS = ["aquite", "colosifite", "emerald", "lapis", "obsid", "quartz", "redstone", "shadow", "ultimate"]
TITLES = {"obsid": "Obsidian"}


def name(key):
    return re.sub("§.", "", LANG.get(key, "")).strip() or key.rsplit(".", 1)[-1]


def num(v):
    return "" if v is None else f"{v:g}"


def row(path):
    item = path.stem
    c = json.loads(path.read_text())["components"]
    mods = {m["type"].split(":")[1]: m["amount"] for m in c.get("minecraft:attribute_modifiers", [])}
    rules = c.get("minecraft:tool", {}).get("rules", [])
    speed = rules[-1].get("speed") if rules else None
    lore = " / ".join(x.get("text", "") for x in c.get("minecraft:lore", []))
    return (item, f"| {name('item.useful_armory.' + item)} | `{item}` | {num(mods.get('attack_damage'))} | "
                  f"{num(mods.get('attack_speed'))} | {num(mods.get('armor'))} | {num(mods.get('armor_toughness'))} | "
                  f"{num(c.get('minecraft:max_damage'))} | {num(speed)} | {lore} |")


def main():
    rows = [row(p) for p in sorted((NS / "item").glob("*.json"))]
    head = ("| Name | Id | Attack damage | Attack speed | Armour | Toughness | Durability | Mining speed | Tooltip |\n"
            "|---|---|---|---|---|---|---|---|---|")
    out = ["# Items and blocks", "",
           "Generated by `tools/item_list.py` from `content/`. Ids are in the `useful_armory:` namespace.",
           "Attack damage and speed are the modifiers on top of the player's base (1 damage, 4 speed).", ""]
    left = list(rows)
    for key in SETS:
        mine = [r for r in left if r[0].startswith(key)]
        left = [r for r in left if r not in mine]
        out += [f"## {TITLES.get(key, key.title())}", "", head, *[r[1] for r in mine], ""]
    out += ["## Special weapons, materials and oddities", "", head, *[r[1] for r in left], ""]
    out += ["## Blocks", "", "| Name | Id | Based on | Hardness |", "|---|---|---|---|"]
    for p in sorted((NS / "block").glob("*.json")):
        d = json.loads(p.read_text())
        out.append(f"| {name('block.useful_armory.' + p.stem)} | `{p.stem}` | `{d['template']}` | "
                   f"{num(d['properties'].get('hardness'))} |")
    (ROOT / "docs" / "items.md").write_text("\n".join(out) + "\n")
    print(f"docs/items.md: {len(rows)} items")


if __name__ == "__main__":
    main()
